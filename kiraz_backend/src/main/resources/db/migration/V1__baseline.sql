--
-- Table: audit_logs
--
CREATE TABLE public.audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    action character varying(255) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    details character varying(2000),
    entity_id bigint,
    entity_name character varying(255) NOT NULL,
    performed_by_role character varying(255),
    performed_by_id bigint,
    CONSTRAINT audit_logs_performed_by_role_check CHECK (performed_by_role IN ('LANDLORD', 'TENANT', 'AGENT'))
);

--
-- Table: lease_agreements
--
CREATE TABLE public.lease_agreements (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    end_date date,
    monthly_rent_amount numeric(38,2) NOT NULL,
    payment_day integer,
    start_date date,
    property_id bigint NOT NULL,
    tenant_id bigint NOT NULL,
    contract_file_url character varying(255),
    invite_code character varying(255),
    status character varying(255),
    deposit_amount numeric(38,2),
    approval_status character varying(255),
    rejection_reason character varying(255),
    created_by_id bigint,
    contract_file_path character varying(255),
    invite_code_expires_at timestamp(6) without time zone,
    invite_code_used boolean,
    invite_code_used_at timestamp(6) without time zone,
    CONSTRAINT lease_agreements_approval_status_check CHECK (approval_status IN ('PENDING_LANDLORD_APPROVAL', 'ACTIVE', 'REJECTED', 'TERMINATED')),
    CONSTRAINT lease_agreements_status_check CHECK (status IN ('PENDING', 'ACTIVE', 'CANCELLED'))
);

--
-- Table: notifications
--
CREATE TABLE public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    is_read boolean NOT NULL,
    message character varying(1000) NOT NULL,
    title character varying(255) NOT NULL,
    user_id bigint NOT NULL,
    reference_id bigint,
    type character varying(255)
);

--
-- Table: properties
--
CREATE TABLE public.properties (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    address character varying(255),
    city character varying(255),
    created_at timestamp(6) without time zone NOT NULL,
    title character varying(255) NOT NULL,
    landlord_id bigint NOT NULL,
    dask_end_date date,
    status character varying(255)
);

--
-- Table: property_delegations
--
CREATE TABLE public.property_delegations (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    end_date date,
    revocation_reason character varying(255),
    revoked_at timestamp(6) without time zone,
    start_date date,
    status character varying(255) NOT NULL,
    agent_id bigint NOT NULL,
    granted_by_id bigint NOT NULL,
    property_id bigint NOT NULL,
    CONSTRAINT property_delegations_status_check CHECK (status IN ('ACTIVE', 'REVOKED', 'EXPIRED'))
);

--
-- Table: refresh_tokens
--
CREATE TABLE public.refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    expiry_date timestamp(6) with time zone NOT NULL,
    revoked boolean NOT NULL,
    token_hash character varying(128) NOT NULL,
    user_id bigint NOT NULL
);

--
-- Table: rent_periods
--
CREATE TABLE public.rent_periods (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    month integer,
    payment_date date,
    receipt_image_url character varying(255),
    status character varying(255) NOT NULL,
    year integer,
    lease_id bigint NOT NULL,
    period_start date,
    receipt_file_path character varying(255)
);

--
-- Table: users
--
CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email character varying(255) NOT NULL,
    full_name character varying(255),
    password_hash character varying(255),
    phone character varying(255),
    reference_code character varying(255),
    role character varying(255),
    CONSTRAINT users_role_check CHECK (role IN ('LANDLORD', 'TENANT', 'AGENT'))
);

